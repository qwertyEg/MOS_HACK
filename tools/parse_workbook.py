#!/usr/bin/env python3
"""Разбор «Сводного перечня строительных работ» в машинночитаемый вид.

Делает три вещи:
  1. Чинит баг исходного файла: коды уровня 2 («10.1.», «12.3.») Excel
     автоконвертировал в даты (45667 → 10.01.2025). Восстанавливаем как d.m.
  2. Восстанавливает иерархию: строки без кода принадлежат последней
     пронумерованной строке.
  3. Раскладывает работы по 7 макроэтапам, видимым с камеры, и помечает
     исключённые (внутренние работы, поставка оборудования, дорожная специфика).

Правила сопоставления заданы явно, таблицей, а не эвристикой — чтобы на защите
на вопрос «почему эта работа отнесена к монолиту» был ответ из данных.

    python tools/parse_workbook.py
"""

import csv
import datetime
import sys
from pathlib import Path

import openpyxl

SRC = Path("materials/Сводный перечень строительных работ_ЛТЦ.xlsx")
OUT_DIR = Path("reference")

OBJECT_TYPES = [
    "Жильё", "Образование", "Здравоохранение", "Спорт", "Культура",
    "Административные здания", "ДОУ", "Офисно-деловой центр", "Дороги",
]

# Кровля и фасад — один макроэтап, а не два. Причина в наблюдаемости, а не
# в технологии: с трёх камер датасета кровля высокого здания в кадр почти не
# попадает, и «готова ли кровля» по снимку не ответить. Фасад же виден всегда
# и идёт с кровлей практически одновременно, так что разделять их значило бы
# завести этап, который камера не умеет подтвердить.
MACRO_STAGES = {
    1: "Подготовка территории",
    2: "Ограждение котлована, шпунт, сваи",
    3: "Земляные работы, котлован",
    4: "Монолит подземной части",
    5: "Монолит надземной части",
    6: "Кровля, фасад и остекление",
    7: "Благоустройство",
}

# Причины исключения — для документа «Условия и ограничения».
EXCL_INTERNAL = "внутренние работы, организаторы разрешили игнорировать"
EXCL_SUPPLY = "заказ и поставка, не строительная работа"
EXCL_ROAD = "специфика линейных объектов, вне скоупа прототипа"
EXCL_TUNNEL = "тоннелепроходка, вне скоупа прототипа"

# Код (префикс) → макроэтап, либо (0, причина) для исключённых.
# Порядок не важен: берётся самый длинный совпавший префикс.
CODE_MAP: dict[str, int | tuple[int, str]] = {
    "10.": 1,

    "12.1.": (0, EXCL_TUNNEL),
    "12.2.": (0, EXCL_TUNNEL),

    "12.3.1.": 3,       # устройство котлована
    "12.3.2.": 2,       # устройство свай
    "12.3.3.": 3,       # устройство основания
    "12.3.4.": 4,       # устройство фундамента
    "12.3.5.": 2,       # ограждающие конструкции СВГ, БСС
    "12.3.6.": 2,       # ограждающие конструкции котлована
    "12.3.7.": 3,       # земляные работы
    "12.3.8.": (0, EXCL_ROAD),
    "12.3.9.": 4,       # монолитные работы ниже отметки 0
    "12.3.10.": 4,      # гидроизоляция подземной части
    "12.3.11.": 4,      # инъектирование стен подвала

    "12.4.1.": (0, EXCL_SUPPLY),
    "12.4.2.": (0, EXCL_SUPPLY),
    "12.4.3.": (0, EXCL_SUPPLY),
    "12.4.4.": 5,       # несущие ж/б конструкции надземной части
    "12.4.5.": 5,       # армокаркас
    "12.4.6.": 5,       # опоры
    "12.4.7.": 5,       # пролёты
    "12.4.8.": 5,       # стены и перегородки — см. REVIEW
    "12.4.9.": 5,       # бетонирование плиты и стен
    "12.4.10.": 5,      # бетонирование колонн и перекрытий
    "12.4.11.": 6,      # фасад
    "12.4.28.": 5,      # монолитные работы выше отметки 0
    "12.4.29.": 5,      # каркас здания
    "12.4.30.": 5,      # металлоконструкции
    "12.4.31.": 6,      # устройство пирога кровли
    "12.4.32.": 6,      # устройство конструкций кровли
    "12.4.33.": (0, EXCL_INTERNAL),   # ворота
    "12.4.34.": (0, EXCL_INTERNAL),   # двери деревянные
    "12.4.35.": (0, EXCL_INTERNAL),   # внутренние металлические двери
    "12.4.36.": 6,      # наружные двери
    "12.4.37.": 6,      # алюминиевые витражи
    "12.4.38.": 6,      # оконные блоки ПВХ
    "12.4.39.": (0, EXCL_INTERNAL),   # алюминиевые подоконники
    "12.4.40.": (0, EXCL_INTERNAL),   # подоконники ГКЛВ
    "12.4.50.": (0, EXCL_INTERNAL),   # облицовка приямков изнутри

    "12.5.": (0, EXCL_INTERNAL),      # инженерные системы целиком
    "12.6.": (0, EXCL_INTERNAL),      # отделочные работы целиком
    "12.7.": 7,                       # благоустройство целиком
}

# 12.4.12 – 12.4.27 — дорожная одежда, разметка, знаки, светофоры, экраны.
for _n in range(12, 28):
    CODE_MAP[f"12.4.{_n}."] = (0, EXCL_ROAD)
# 12.4.41 – 12.4.57 — утепление, навесной фасад, облицовка, ламели, козырьки.
for _n in list(range(41, 50)) + list(range(51, 58)):
    CODE_MAP[f"12.4.{_n}."] = 6

# Строки без кода наследуют макроэтап родителя. Исключения — когда
# отдельная строка внутри раздела содержательно относится к другому этапу.
#
# Формат: (область действия или None, ключевое слово, этап, обоснование).
# Область — префикс кода: правило применяется только внутри этого раздела.
# Это нужно там, где раздел справочника смешивает видимые и внутренние работы:
# «Стены и перегородки» содержит и наружную кладку, и гипсокартон.
# Проверяется по вхождению в название, регистр игнорируется, первое совпадение.
KEYWORD_OVERRIDES: list[tuple[str | None, str, int, str]] = [
    # Нулевой цикл: свайные и шпунтовые работы разнесены по разделам вперемешку
    (None, "шпунтовое ограждение", 2, "шпунт — ограждение котлована, не земляные работы"),
    (None, "буронабивные сваи", 2, "сваи"),
    (None, "буроинъекционные сваи", 2, "сваи"),
    (None, "свайного фундамента", 2, "свайные работы предшествуют бетонированию"),
    (None, "разработка грунта с креплением", 3, "земляные работы"),
    (None, "выемка грунта", 3, "земляные работы"),
    (None, "фундамент под башенный кран", 4, "часть фундаментных работ"),

    # 12.4.8 «Стены и перегородки» — раздел смешанный, делим построчно.
    # Порядок важен: сначала отсекаем заведомо внутреннее, потом ловим наружное.
    ("12.4.8.", "гкл", 0, "гипсокартон — внутренняя работа"),
    ("12.4.8.", "гвл", 0, "ГВЛВ — внутренняя работа"),
    ("12.4.8.", "сантехнич", 0, "сантехнические перегородки — внутренняя работа"),
    ("12.4.8.", "люк", 0, "ревизионные люки — внутренняя работа"),
    ("12.4.8.", "внутренн", 0, "внутренние перегородки не видны с камеры"),
    ("12.4.8.", "наружн", 6, "наружные стены — видимая оболочка здания"),
    ("12.4.8.", "кладка стен", 6, "кладка наружных стен видна с камеры"),
    ("12.4.8.", "сэндвич-панел", 6, "стеновые сэндвич-панели — видимая оболочка"),

    # 12.4.30 «Металлоконструкции» — каркас, но кровельное покрытие отдельно.
    ("12.4.30.", "профилированного листа", 6, "покрытие кровли профлистом"),
]

# Заголовки разделов — не работы, а контейнеры. Своего этапа не имеют.
CONTAINERS = {"12", "12.", "12.3.", "12.4."}

# Строки, где автоматическое решение спорное и нужен взгляд инженера.
REVIEW: dict[str, str] = {
    "12.4.8.": "«Стены и перегородки» — наружные стены видны (этап 6), "
               "внутренние перегородки нет. Раздел смешанный, нужно решить",
    "12.4.30.": "«Металлоконструкции» — может быть каркас (этап 5), "
                "а может кровля или фасад",
    "12.3.4.": "«Устройство фундамента» содержит и свайные работы (этап 2), "
               "и бетонирование (этап 4)",
    "10.13.": "Оснащение стройплощадки камерами — формально этап 1, "
              "но это наш же источник данных, не наблюдаемая работа",
}


def fix_code(raw) -> str:
    """Восстанавливает код из значения ячейки, чиня date-serial."""
    if raw is None:
        return ""
    if isinstance(raw, datetime.datetime):
        return f"{raw.day}.{raw.month}."
    return str(raw).strip()


def lookup(code: str) -> tuple[int, str]:
    """Макроэтап по коду: самый длинный совпавший префикс."""
    if code in CONTAINERS:
        return -2, "заголовок раздела"
    best = ""
    for prefix in CODE_MAP:
        if code.startswith(prefix) and len(prefix) > len(best):
            best = prefix
    if not best:
        return -1, "нет правила"
    value = CODE_MAP[best]
    if isinstance(value, tuple):
        return value[0], value[1]
    return value, f"правило {best}"


def main() -> int:
    if not SRC.exists():
        print(f"нет файла {SRC}", file=sys.stderr)
        return 1

    ws = openpyxl.load_workbook(SRC, data_only=True)["Лист1"]
    rows: list[dict] = []
    parent_code = ""
    parent_stage = -1
    parent_reason = ""

    for r in range(4, ws.max_row + 1):
        code = fix_code(ws.cell(r, 1).value)
        name = ws.cell(r, 2).value
        name = "" if name is None else str(name).strip()
        if not code and not name:
            continue

        types = [OBJECT_TYPES[i] for i in range(9) if ws.cell(r, 3 + i).value]

        if code:
            parent_code = code
            stage, reason = lookup(code)
            parent_stage, parent_reason = stage, reason
            level = code.rstrip(".").count(".") + 1
            own_code = code
        else:
            # Строка-детализация: наследует родителя, если нет переопределения.
            stage, reason = parent_stage, f"наследует {parent_code}"
            level = 0
            own_code = ""

        low = name.lower()
        section = own_code or parent_code
        for scope, kw, kw_stage, kw_reason in KEYWORD_OVERRIDES:
            if scope and not section.startswith(scope):
                continue
            if kw in low:
                stage, reason = kw_stage, f"переопределено: {kw_reason}"
                break

        rows.append({
            "row": r,
            "code": own_code,
            "parent_code": "" if own_code else parent_code,
            "level": level,
            "name": name,
            "macro_stage_id": stage,
            "macro_stage": MACRO_STAGES.get(stage, {0: "ИСКЛЮЧЕНО", -2: "раздел"}.get(stage, "БЕЗ ПРАВИЛА")),
            "reason": reason,
            "object_types": "|".join(types),
            "review": next((t for p, t in REVIEW.items()
                            if (own_code or parent_code).startswith(p)), ""),
        })

    OUT_DIR.mkdir(exist_ok=True)
    fields = ["row", "code", "parent_code", "level", "name", "macro_stage_id",
              "macro_stage", "reason", "object_types", "review"]
    with (OUT_DIR / "work_types.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)

    # Отдельный короткий файл на ревью — только спорное и непокрытое.
    flagged = [r for r in rows if r["review"] or r["macro_stage_id"] == -1]
    with (OUT_DIR / "work_types_review.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(flagged)

    # Сводка
    print(f"строк разобрано: {len(rows)}")
    print(f"\n{'этап':>5}  {'строк':>6}  название")
    counts: dict[int, int] = {}
    for r in rows:
        counts[r["macro_stage_id"]] = counts.get(r["macro_stage_id"], 0) + 1
    for sid in sorted(counts):
        label = MACRO_STAGES.get(sid, {0: "ИСКЛЮЧЕНО", -2: "заголовок раздела"}.get(sid, "БЕЗ ПРАВИЛА"))
        print(f"{sid:>5}  {counts[sid]:>6}  {label}")

    kept = sum(v for k, v in counts.items() if k > 0)
    print(f"\nоставляем {kept} из {len(rows)} строк "
          f"({kept / len(rows):.0%}), остальное — внутренние работы и вне скоупа")
    print(f"на ревью: {len(flagged)} строк → {OUT_DIR / 'work_types_review.csv'}")
    print(f"полная таблица → {OUT_DIR / 'work_types.csv'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
