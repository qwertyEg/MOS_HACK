HEADER = ("№ п/п", "Вид работ", "Начало", "Окончание", "Длительность, дн.", "Техника")


def _excel_code(code: str):
    """Код второго уровня так, как его сохранил бы Excel: дата «d.m.» (10.2. → 10 февраля 2025)."""
    parts = [p for p in code.rstrip(".").split(".") if p]
    if len(parts) == 2:
        day, month = int(parts[0]), int(parts[1])
        if 1 <= month <= 12 and 1 <= day <= 31:
            return dt.datetime(2025, month, day)
    return code


def build(path: Path = SAMPLE_PATH) -> Path:
    import openpyxl
    from openpyxl.styles import Font

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "График"
    ws.append([])
    ws.append(["Календарный график строительства: жилой дом, 17 этажей (пример для СтройВзора)"])
    ws.append(list(HEADER))
    for cell in ws[3]:
        cell.font = Font(bold=True)
    for code, name, start, end, equipment in ROWS:
        dur = (end - start).days + 1 if start and end else None
        ws.append([_excel_code(code) if code else None, name, start, end, dur, equipment or None])
        r = ws.max_row
        if isinstance(ws.cell(r, 1).value, dt.datetime):
            ws.cell(r, 1).number_format = "d\\.m\\."
        for c in (3, 4):
            ws.cell(r, c).number_format = "DD.MM.YYYY"
        if code and code.count(".") <= 2:
            ws.cell(r, 2).font = Font(bold=True)
    for col, width in zip("ABCDEF", (10, 60, 12, 12, 10, 60)):
        ws.column_dimensions[col].width = width
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


if __name__ == "__main__":
    print(build())
